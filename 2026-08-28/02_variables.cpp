#include <iostream>

int main () {
    float flotante = 0.9f;
    int entera = 9;
    std::cout << "Multiplicacion: " << (flotante * entera) << std::endl; 
    std::cout << "Suma: " << (flotante + entera) << std::endl;
    std::cout << "Division: " << (flotante / entera) << std::endl;
    std::cout << "Resta: " << (flotante - entera) << std::endl;
}